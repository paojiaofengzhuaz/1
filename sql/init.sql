DROP TABLE IF EXISTS `resume`;
CREATE TABLE `resume` (
    id               BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id          BIGINT NOT NULL COMMENT '求职者ID',
    name             VARCHAR(50)  NOT NULL COMMENT '姓名',
    gender           VARCHAR(10)  COMMENT '性别',
    age              INT          COMMENT '年龄',
    phone            VARCHAR(20)  COMMENT '电话',
    email            VARCHAR(100) COMMENT '邮箱',
    education        VARCHAR(20)  COMMENT '学历',
    experience_years INT          DEFAULT 0 COMMENT '工作年限',
    city             VARCHAR(30)  COMMENT '期望城市',
    salary           INT          COMMENT '期望薪资(K)',
    skills           VARCHAR(255) COMMENT '技能，逗号分隔',
    self_intro       VARCHAR(500) COMMENT '自我介绍',
    update_time      DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE = InnoDB COMMENT '简历表';

