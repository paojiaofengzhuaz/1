-- ---------------- 沟通库 ----------------
USE recruit_im;
DROP TABLE IF EXISTS `conversation`;
CREATE TABLE `conversation` (
    id         BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_a     BIGINT       NOT NULL COMMENT '求职者ID',
    user_b     BIGINT       NOT NULL COMMENT '招聘者ID',
    job_id     BIGINT       COMMENT '关联岗位',
    job_title  VARCHAR(100) COMMENT '岗位名称',
    last_msg   VARCHAR(255) COMMENT '最后一条消息',
    last_time  DATETIME     DEFAULT CURRENT_TIMESTAMP,
    unread_a   INT          DEFAULT 0 COMMENT '求职者未读数',
    unread_b   INT          DEFAULT 0 COMMENT '招聘者未读数'
) ENGINE = InnoDB COMMENT '会话表';

DROP TABLE IF EXISTS `message`;
CREATE TABLE `message` (
    id          BIGINT AUTO_INCREMENT PRIMARY KEY,
    conv_id     BIGINT       NOT NULL COMMENT '会话ID',
    from_id     BIGINT       NOT NULL COMMENT '发送人',
    to_id       BIGINT       NOT NULL COMMENT '接收人',
    content     VARCHAR(1000) NOT NULL,
    read_flag   TINYINT      DEFAULT 0,
    create_time DATETIME     DEFAULT CURRENT_TIMESTAMP
) ENGINE = InnoDB COMMENT '消息表';
