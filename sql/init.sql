-- ---------------- 岗位库 ----------------
USE recruit_job;
DROP TABLE IF EXISTS `job`;
CREATE TABLE `job` (
    id          BIGINT AUTO_INCREMENT PRIMARY KEY,
    title       VARCHAR(100) NOT NULL COMMENT '岗位名称',
    category    VARCHAR(30)  NOT NULL DEFAULT '其他' COMMENT '行业分类',
    company     VARCHAR(100) NOT NULL COMMENT '公司',
    city        VARCHAR(30)  NOT NULL COMMENT '城市',
    salary_min  INT          NOT NULL COMMENT '薪资下限(K)',
    salary_max  INT          NOT NULL COMMENT '薪资上限(K)',
    education   VARCHAR(20)  DEFAULT '本科' COMMENT '学历要求',
    experience  VARCHAR(20)  DEFAULT '1-3年' COMMENT '经验要求',
    tags        VARCHAR(255) COMMENT '技能标签，逗号分隔',
    description TEXT COMMENT '岗位描述',
    requirement TEXT COMMENT '任职要求',
    hr_id       BIGINT       COMMENT '发布人ID',
    hr_name     VARCHAR(50)  COMMENT '发布人',
    status      TINYINT      DEFAULT 1 COMMENT '1在招 0下线',
    create_time DATETIME     DEFAULT CURRENT_TIMESTAMP,
    KEY idx_job_category (category),
    KEY idx_job_city (city),
    KEY idx_job_status (status)
) ENGINE = InnoDB COMMENT '岗位表';

